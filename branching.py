# Branching rules: decompose an irrep of a simple Lie algebra G into irreps of a subalgebra H = H_1 x ... x U(1)^k.
#
# An embedding of H in G is described by its projection matrix: a linear map from the weights of G (Dynkin labels) to
# the weights of H (the Dynkin labels of each simple factor and a charge for each U(1), in the order of the factors).
# To branch an irrep of G, project all its weights and peel off the H irreps from the top: the highest projected
# weight is the highest weight of an H irrep, whose weights are then removed, and so on.
#
# The projection matrices are not copied from tables. They are built from the embeddings themselves:
#   - regular subalgebras, from a set of roots of G (deleting nodes of the extended Dynkin diagram, Borel-de Siebenthal,
#     and deleting nodes of the ordinary diagram, which gives a U(1) for each deleted node),
#   - subalgebras of SU(N), SO(N) and Sp(N), from the way the defining representation of G branches,
#   - the principal SU(2) of any G,
#   - compositions G > H > K, and lifts: if K is a subalgebra of both G and H with rank K = rank H, the embedding of H
#     in G follows from those of K in G and K in H (used for E6 > F4, E8 > G2 x F4 and the other special embeddings in
#     exceptional algebras).
# Each embedding is checked when it is built: the projected weights must be integral and the adjoint of G must contain
# the adjoint of every simple factor of H and a singlet for every U(1).

