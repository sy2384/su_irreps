class U1():  # A U(1) factor of a subalgebra; its 'labels' are a single charge
    rank = 1
    name = 'U(1)'
    series = 'U'

    def __eq__(self, other):
        return isinstance(other, U1)

    def __hash__(self):
        return hash('U(1)')

    def __repr__(self):
        return 'U(1)'


def is_u1(factor):
    return isinstance(factor, U1)


def algebra_name(factors):
    return '×'.join(f.name for f in factors)


# ---- root system data that lie_algebra_CG does not keep ----

# Inner products (alpha_i, alpha_j) of the simple roots, normalized so that long roots have length^2 = 2
@lru_cache(maxsize=None)
def root_products(algebra):
    roots = simple_root_vectors(algebra.series, algebra.rank)
    m = [[dot(a, b) for b in roots] for a in roots]
    scale = Fraction(2) / max(m[i][i] for i in range(algebra.rank))
    return tuple(tuple(x * scale for x in row) for row in m)


@lru_cache(maxsize=None)
def cartan_inverse(algebra):
    return tuple(tuple(row) for row in invert(algebra.cartan))


# Coordinates of a weight in the basis of simple roots: lambda = sum_k c_k alpha_k, and c_k = <lambda, omega_k^vee>
def root_coordinates(algebra, weight):
    inverse = cartan_inverse(algebra)
    return tuple(sum((weight[j] * inverse[j][k] for j in range(algebra.rank)), Fraction(0))
                 for k in range(algebra.rank))


# (lambda, mu) for weights in Dynkin coordinates, with long roots of length^2 = 2
def inner(algebra, u, v):
    lengths = [root_products(algebra)[i][i] for i in range(algebra.rank)]
    c = root_coordinates(algebra, v)
    return sum((u[i] * c[i] * lengths[i] / 2 for i in range(algebra.rank)), Fraction(0))


def adjoint_labels(algebra):
    return max(algebra.positive_roots, key=lambda alpha: sum(algebra.weight_to_root(alpha)))


# Highest root in the basis of simple roots
def highest_root(algebra):
    return root_coordinates(algebra, adjoint_labels(algebra))


def dimension_of(algebra):
    return algebra.rank + 2 * len(algebra.positive_roots)


# Second-order (Dynkin) index, normalized as in Slansky: 1 for the defining representation of SU(N)
def dynkin_index(algebra, labels):
    rho = (1,) * algebra.rank
    shifted = tuple(a + 2 * r for a, r in zip(labels, rho))
    return Fraction(algebra.dimension(tuple(labels))) * inner(algebra, labels, shifted) / dimension_of(algebra)


WEYL_ORDERS = {'G2': 12, 'F4': 1152, 'E6': 51840, 'E7': 2903040, 'E8': 696729600}


def weyl_group_order(series, rank):
    if series == 'A':
        return factorial(rank + 1)
    if series in 'BC':
        return 2 ** rank * factorial(rank)
    if series == 'D':
        return 2 ** (rank - 1) * factorial(rank)
    return WEYL_ORDERS[series + str(rank)]


# Number of distinct weights of an irrep, without listing them: the sum of |W| / |W_mu| over its dominant weights,
# where W_mu is generated by the simple reflections that fix mu. The dominant weights are those reached from the highest
# weight by subtracting positive roots (Stembridge); no multiplicities are needed. Stops early once past 'stop'.
def number_of_weights(algebra, labels, stop=None):
    order = weyl_group_order(algebra.series, algebra.rank)
    seen = {tuple(labels)}
    layer = [tuple(labels)]
    total = 0
    while layer:
        next_layer = []
        for mu in layer:
            fixed = [i for i in range(algebra.rank) if mu[i] == 0]
            stabilizer = 1
            for series, rank, _ in identify_diagram([[algebra.cartan[i][j] for j in fixed] for i in fixed]):
                stabilizer *= weyl_group_order(series, rank)
            total += order // stabilizer
            if stop is not None and total > stop:
                return total
            for alpha in algebra.positive_roots:
                nu = tuple(a - b for a, b in zip(mu, alpha))
                if min(nu) >= 0 and nu not in seen:
                    seen.add(nu)
                    next_layer.append(nu)
        layer = next_layer
    return total


# ---- Dynkin diagrams ----

@lru_cache(maxsize=None)
def standard_cartan(series, rank):
    return SimpleLieAlgebra(series, rank).cartan


def candidate_types(size):
    types = [('A', size)]
    if size >= 2:
        types += [('B', size), ('C', size)]
    if size >= 3:
        types.append(('D', size))
    if size in (6, 7, 8):
        types.append(('E', size))
    if size == 4:
        types.append(('F', 4))
    if size == 2:
        types.append(('G', 2))
    return types


# Ways of reading the nodes 'nodes' of the Cartan matrix 'cartan' as the Dynkin diagram of (series, rank) in Bourbaki
# order. Returns the first ordering found (nodes taken in increasing order), or None.
def match_diagram(cartan, nodes, series, rank):
    if len(nodes) != rank:
        return None
    target = standard_cartan(series, rank)
    order = []

    def extend():
        a = len(order)
        if a == rank:
            return True
        for node in nodes:
            if node in order:
                continue
            if cartan[node][node] != target[a][a]:
                continue
            if all(cartan[node][order[b]] == target[a][b] and cartan[order[b]][node] == target[b][a]
                   for b in range(a)):
                order.append(node)
                if extend():
                    return True
                order.pop()
        return False

    return tuple(order) if extend() else None


def components(cartan):
    n = len(cartan)
    seen = set()
    result = []
    for start in range(n):
        if start in seen:
            continue
        stack, comp = [start], []
        seen.add(start)
        while stack:
            i = stack.pop()
            comp.append(i)
            for j in range(n):
                if j not in seen and (cartan[i][j] or cartan[j][i]):
                    seen.add(j)
                    stack.append(j)
        result.append(sorted(comp))
    return result


# Split a Cartan matrix into simple components: a list of (series, rank, node order), the components ordered by their
# smallest node. Each component gets the first matching type in the order A, B, C, D, E, F, G (so B2 rather than C2,
# A3 rather than D3).
def identify_diagram(cartan):
    result = []
    for comp in components(cartan):
        for series, rank in candidate_types(len(comp)):
            order = match_diagram(cartan, comp, series, rank)
            if order is not None:
                result.append((series, rank, order))
                break
        else:
            raise ValueError("Not a Cartan matrix of a semisimple Lie algebra: {}".format(cartan))
    return result


# Cartan matrix of a list of roots of G given in the basis of simple roots
def cartan_of_roots(algebra, roots):
    m = root_products(algebra)
    n = algebra.rank

    def product_of(a, b):
        return sum((a[i] * m[i][j] * b[j] for i in range(n) for j in range(n) if a[i] and b[j]), Fraction(0))

    norms = [product_of(r, r) for r in roots]
    cartan = []
    for a, r in enumerate(roots):
        row = []
        for b, s in enumerate(roots):
            value = 2 * product_of(r, s) / norms[b]
            if value.denominator != 1:
                raise ValueError("These vectors are not roots of {}".format(algebra.name))
            row.append(int(value))
        cartan.append(row)
    return cartan


# ---- irreps of a product of simple factors and U(1)s ----

class SubIrrep():
    """An irrep of H = H_1 x ... x U(1)^k: a LieIrrep for each simple factor and a charge for each U(1)."""

    def __init__(self, factors, parts):
        self.factors = tuple(factors)
        self.parts = tuple(Fraction(p) if is_u1(f) else p for f, p in zip(factors, parts))

    @property
    def irreps(self):
        return tuple(p for f, p in zip(self.factors, self.parts) if not is_u1(f))

    @property
    def charges(self):
        return tuple(p for f, p in zip(self.factors, self.parts) if is_u1(f))

    @property
    def dim(self):
        return prod(irrep.dim for irrep in self.irreps)

    @property
    def labels(self):
        return tuple(p if isinstance(p, Fraction) else p.labels for p in self.parts)

    def weights(self):
        result = Counter({(): 1})
        for f, p in zip(self.factors, self.parts):
            if is_u1(f):
                result = Counter({w + (p,): m for w, m in result.items()})
            else:
                result = Counter({w + v: m * n for w, m in result.items() for v, n in p.weights().items()})
        return result

    def __eq__(self, other):
        return isinstance(other, SubIrrep) and (self.factors, self.parts) == (other.factors, other.parts)

    def __hash__(self):
        return hash((self.factors, self.parts))

    def sort_key(self):
        return (-self.dim, tuple(-x for irrep in self.irreps for x in irrep.labels), tuple(-q for q in self.charges))

    # Slansky's notation: dimensions of the simple factors, then the U(1) charges, e.g. (3, 2)(1/6) or 16(-1)
    def __str__(self):
        names = [dimension_name(irrep) for irrep in self.irreps]
        text = ''
        if len(names) == 1:
            text = names[0]
        elif names:
            text = '(' + ', '.join(names) + ')'
        return text + ''.join('({})'.format(q) for q in self.charges)

    # Full form, with Dynkin labels: e.g. (1, 0)[3] x (1)[2] x (1/6)
    def __repr__(self):
        return ' × '.join('({})'.format(p) if isinstance(p, Fraction) else repr(p) for p in self.parts)


# Dimension with primes and a bar, as in Slansky: irreps of the same dimension are told apart by their index (the one
# with the smallest index has no prime), and 'bar' marks the conjugate as in LieIrrep
def dimension_name(irrep):
    level = prime_level(irrep.algebra, irrep.labels)
    return str(irrep.dim) + "'" * level + ('bar' if irrep.bar else '')


# Irreps of the same dimension are ordered by their index, then by their Dynkin labels (largest first); an irrep and
# its conjugate share a level (e.g. SU(3): 15 = (2, 1), 15' = (4, 0); SO(8): 8 = (1, 0, 0, 0), 8' = (0, 0, 1, 0),
# 8'' = (0, 0, 0, 1))
@lru_cache(maxsize=4096)
def prime_level(algebra, labels):
    def key(labels):
        conjugate = algebra.dominant(tuple(-x for x in labels))[0]
        return dynkin_index(algebra, labels), tuple(-x for x in max(labels, conjugate))

    keys = sorted({key(other) for other in irreps_of_dimension(algebra, algebra.dimension(labels))})
    return keys.index(key(labels))


# All irreps of a given dimension. The dimension grows with each Dynkin label, so the search stops early.
@lru_cache(maxsize=1024)
def irreps_of_dimension(algebra, d):
    found = []
    labels = [0] * algebra.rank

    def search(i):
        if i == algebra.rank:
            if algebra.dimension(tuple(labels)) == d:
                found.append(tuple(labels))
            return
        while algebra.dimension(tuple(labels)) <= d:
            search(i + 1)
            labels[i] += 1
        labels[i] = 0

    search(0)
    return tuple(found)


# ---- embeddings ----

class Embedding():
    """A subalgebra H = factors[0] x factors[1] x ... of 'parent' (a tuple of factors, normally one simple algebra),
    given by its projection matrix: row r maps the parent's Dynkin labels to the r-th coordinate of the H weight."""

    def __init__(self, parent, factors, matrix, description=''):
        self.parent = tuple(parent)
        self.factors = tuple(factors)
        self.matrix = tuple(tuple(Fraction(x) for x in row) for row in matrix)
        self.description = description
        if len(self.matrix) != sum(f.rank for f in self.factors) or \
                any(len(row) != sum(f.rank for f in self.parent) for row in self.matrix):
            raise ValueError("The projection matrix has the wrong shape")
        for r in self.simple_rows():
            if any(x.denominator != 1 for x in self.matrix[r]):
                raise ValueError("The projection of {} to {} is not integral".format(algebra_name(self.parent),
                                                                                      self.name))

    @property
    def name(self):
        return algebra_name(self.factors)

    def __repr__(self):
        return "Embedding({} ⊃ {})".format(algebra_name(self.parent), self.name)

    def blocks(self):
        start = 0
        for f in self.factors:
            yield f, range(start, start + f.rank)
            start += f.rank

    def simple_rows(self):
        return [r for f, rows in self.blocks() if not is_u1(f) for r in rows]

    def project(self, weight):
        return tuple(sum((x * w for x, w in zip(row, weight) if w), Fraction(0)) for row in self.matrix)

    def split(self, weight):
        # a projected weight as a tuple of parts (a label tuple per simple factor, a charge per U(1))
        return tuple(weight[rows[0]] if is_u1(f) else tuple(int(weight[r]) for r in rows) for f, rows in self.blocks())

    def subirrep(self, parts):
        return SubIrrep(self.factors, [p if is_u1(f) else LieIrrep(f, p) for f, p in zip(self.factors, parts)])


def parent_weights(embedding, irrep):
    if isinstance(irrep, SubIrrep):
        return irrep.weights()
    if len(embedding.parent) != 1 or is_u1(embedding.parent[0]):
        raise ValueError("Give an irrep of {}".format(algebra_name(embedding.parent)))
    return _weights(embedding.parent[0], tuple(irrep.labels))


# Branch an irrep of the parent (a LieIrrep, or a SubIrrep when the parent is a product) to the subalgebra.
# Returns [(SubIrrep, multiplicity), ...], largest first.
def branch(irrep, embedding, max_weights=None):
    if max_weights is not None and not isinstance(irrep, SubIrrep):
        if number_of_weights(embedding.parent[0], tuple(irrep.labels), stop=max_weights) > max_weights:
            raise ValueError("The irrep ({}) of {} has more than {} distinct weights; too large to branch here"
                             .format(', '.join(str(x) for x in irrep.labels), embedding.parent[0].name, max_weights))
    # Integer arithmetic: each row as integer numerators over a common denominator
    denominators = [lcm(*(x.denominator for x in row)) for row in embedding.matrix]
    rows = [[int(x * d) for x in row] for row, d in zip(embedding.matrix, denominators)]
    simple = embedding.simple_rows()
    projected = Counter()
    for w, m in parent_weights(embedding, irrep).items():
        p = tuple(sum(r * x for r, x in zip(row, w) if x) for row in rows)
        if all(p[i] >= 0 for i in simple):
            projected[p] += m
    blocks = list(embedding.blocks())

    # height of a weight: the sum of its coordinates in the basis of simple roots, over all simple factors
    def height(p):
        return sum(sum(root_coordinates(f, [p[r] for r in rows_])) for f, rows_ in blocks if not is_u1(f))

    def unscale(p):
        return tuple(Fraction(x, d) for x, d in zip(p, denominators))

    terms = []
    for p in sorted(projected, key=height, reverse=True):
        m = projected[p]
        if m == 0:
            continue
        if m < 0:
            raise ValueError("Branching left a negative multiplicity: the projection matrix is not consistent")
        parts = embedding.split(unscale(p))
        sub = embedding.subirrep(parts)
        # remove the dominant weights of this H irrep (a U(1) charge is kept as its scaled numerator)
        dominant = []
        for (f, rows_), part in zip(blocks, parts):
            if is_u1(f):
                dominant.append({(int(part * denominators[rows_[0]]),): 1})
            else:
                dominant.append(_dominant_multiplicities(f, part))
        for combination in product(*(d.items() for d in dominant)):
            key = tuple(x for mu, _ in combination for x in mu)
            mult = prod(n for _, n in combination)
            if key not in projected:
                raise ValueError("Branching failed: the projection matrix is not consistent")
            projected[key] -= m * mult
        terms.append((sub, m))
    return sorted(terms, key=lambda item: item[0].sort_key())


def format_branching(irrep, terms):
    return '{} = {}'.format(dimension_name(irrep) if isinstance(irrep, LieIrrep) else str(irrep),
                            ' + '.join((str(m) + '·' if m > 1 else '') + str(sub) for sub, m in terms))


# ---- checks ----

# The adjoint of G must contain the adjoint of every simple factor of H (as a singlet of the others, charge 0) and a
# singlet for every U(1). Together with the integrality of the projection this catches wrong projection matrices.
def check_embedding(embedding):
    if len(embedding.parent) != 1:
        return embedding
    g = embedding.parent[0]
    terms = dict(branch(LieIrrep(g, adjoint_labels(g)), embedding))
    trivial = [Fraction(0) if is_u1(f) else LieIrrep(f, (0,) * f.rank) for f in embedding.factors]
    needed = Counter()
    for i, f in enumerate(embedding.factors):
        if is_u1(f):
            needed[SubIrrep(embedding.factors, trivial)] += 1
        else:
            parts = list(trivial)
            parts[i] = LieIrrep(f, adjoint_labels(f))
            needed[SubIrrep(embedding.factors, parts)] += 1
    for sub, m in needed.items():
        if terms.get(sub, 0) < m:
            raise ValueError("Not a subalgebra: the adjoint of {} does not contain {}".format(g.name, sub))
    return embedding


# ---- building embeddings ----

# Regular subalgebra spanned by root vectors. 'factor_roots' holds, for each simple factor, its simple roots (as roots
# of G in the basis of simple roots of G) in the Bourbaki order of 'types[i]' (found automatically when omitted).
# 'coweights' gives each U(1) as an element of the Cartan subalgebra, in the basis of fundamental coweights; it must
# be orthogonal to all the roots. The label of a weight lambda for the simple root beta is <lambda, beta^vee>.
def regular_embedding(algebra, factor_roots, coweights=(), types=None, description='', normalize=True):
    n = algebra.rank
    lengths = [root_products(algebra)[i][i] for i in range(n)]
    factors, rows = [], []
    for k, roots in enumerate(factor_roots):
        cartan = cartan_of_roots(algebra, roots)
        if types is None:
            found = identify_diagram(cartan)
            if len(found) != 1 or found[0][2] != tuple(range(len(roots))):
                raise ValueError("Roots {} are not the simple roots of one simple factor in Bourbaki order"
                                 .format(roots))
            series, rank = found[0][:2]
        else:
            series, rank = types[k]
            if match_diagram(cartan, list(range(len(roots))), series, rank) != tuple(range(len(roots))):
                raise ValueError("Roots {} are not the simple roots of {}{} in Bourbaki order".format(roots, series,
                                                                                                     rank))
        factors.append(SimpleLieAlgebra(series, rank))
        m = root_products(algebra)
        for beta in roots:
            norm = sum((beta[i] * m[i][j] * beta[j] for i in range(n) for j in range(n)), Fraction(0))
            rows.append([beta[i] * lengths[i] / norm for i in range(n)])
    inverse = cartan_inverse(algebra)
    all_roots = [beta for roots in factor_roots for beta in roots]
    for h in coweights:
        if any(sum(b * x for b, x in zip(beta, h)) != 0 for beta in all_roots):
            raise ValueError("The U(1) generator {} does not commute with the subalgebra".format(h))
        row = [sum((inverse[j][k] * h[k] for k in range(n)), Fraction(0)) for j in range(n)]
        rows.append(normalized_charges(row) if normalize else row)
        factors.append(U1())
    return check_embedding(Embedding([algebra], factors, rows, description))


# Scale a U(1) row so that the charges of all weights of G are integers with no common factor (keeps the sign)
def normalized_charges(row):
    row = [Fraction(x) for x in row]
    if not any(row):
        raise ValueError("Zero U(1) generator")
    common = lcm(*(x.denominator for x in row))
    g = reduce(gcd, (int(x * common) for x in row))
    return [x * common / g for x in row]


# Extended Dynkin diagram: the simple roots and minus the highest root, as node 0
def extended_roots(algebra):
    n = algebra.rank
    return [tuple(-x for x in highest_root(algebra))] + [tuple(Fraction(int(i == j)) for j in range(n))
                                                         for i in range(n)]


def nullspace(vectors, n):
    # basis of {h : v . h = 0 for all v}, by Gauss-Jordan elimination
    m = [[Fraction(x) for x in v] for v in vectors]
    pivots = []
    r = 0
    for c in range(n):
        pivot = next((i for i in range(r, len(m)) if m[i][c] != 0), None)
        if pivot is None:
            continue
        m[r], m[pivot] = m[pivot], m[r]
        m[r] = [x / m[r][c] for x in m[r]]
        for i in range(len(m)):
            if i != r and m[i][c] != 0:
                m[i] = [a - m[i][c] * b for a, b in zip(m[i], m[r])]
        pivots.append(c)
        r += 1
    basis = []
    for free in (c for c in range(n) if c not in pivots):
        h = [Fraction(0)] * n
        h[free] = Fraction(1)
        for i, c in enumerate(pivots):
            h[c] = -m[i][free]
        basis.append(h)
    return basis


# Regular subalgebra from deleting nodes: 'extended' is a node of the extended Dynkin diagram to delete (0 is the
# extra node, None for none), 'deleted' are nodes 1..rank of the ordinary diagram to delete, each giving a U(1).
def deleted_nodes_embedding(algebra, extended=None, deleted=()):
    roots = extended_roots(algebra)
    nodes = list(range(1, algebra.rank + 1))
    if extended:
        nodes = [0] + [i for i in nodes if i != extended]
    kept = [i for i in nodes if i not in deleted]
    kept_roots = [roots[i] for i in kept]
    cartan = cartan_of_roots(algebra, kept_roots)
    found = identify_diagram(cartan)
    factor_roots = [[kept_roots[i] for i in order] for _, _, order in found]
    types = [(s, r) for s, r, _ in found]
    if not extended:
        coweights = [[Fraction(int(i == d)) for i in range(1, algebra.rank + 1)] for d in deleted]
    else:
        coweights = nullspace(kept_roots, algebra.rank)
    if extended:
        what = "node {} of the extended Dynkin diagram".format(extended)
        if deleted:
            what += " and node(s) {}".format(', '.join(str(d) for d in deleted))
    else:
        what = "node(s) {} of the Dynkin diagram".format(', '.join(str(d) for d in deleted))
    description = "regular subalgebra: delete {} (Bourbaki numbering)".format(what)
    return regular_embedding(algebra, factor_roots, coweights, types, description)


# Weights of a list of irreps of the factors (each a tuple of parts: labels for a simple factor, charge for a U(1))
def weights_of(factors, components):
    result = Counter()
    for parts in components:
        sub = SubIrrep(factors, [p if is_u1(f) else LieIrrep(f, p) for f, p in zip(factors, parts)])
        result.update(sub.weights())
    return result


# Subalgebra of SU(N), SO(N) or Sp(N) given by the branching of the defining representation of G: 'components' lists
# the irreps of H that it splits into. Any assignment of their weights to the weights +-e_i of the defining
# representation gives the same branching rules (up to the Weyl group of G), except for SO(2n), where flipping one sign
# exchanges the two spinors; 'flip' does that.
def defining_rep_embedding(algebra, factors, components, description='', flip=False, normalize=True):
    factors = tuple(factors)
    weights = weights_of(factors, components)
    size = sum(weights.values())
    n = algebra.rank
    vectors = simple_root_vectors(algebra.series, n)
    inverse = cartan_inverse(algebra)
    omegas = [[sum((inverse[i][k] * vectors[k][j] for k in range(n)), Fraction(0)) for j in range(len(vectors[0]))]
              for i in range(n)]
    listed = [w for w, m in sorted(weights.items()) for _ in range(m)]
    if algebra.series == 'A':
        if size != n + 1:
            raise ValueError("SU({}) needs {} weights, got {}".format(n + 1, n + 1, size))
        if any(sum(w[r] for w in listed) != 0 for r in range(len(listed[0]))):
            raise ValueError("The U(1) charges must add up to 0")
        images = listed
    elif algebra.series in 'BCD':
        expected = 2 * n + 1 if algebra.series == 'B' else 2 * n
        if size != expected:
            raise ValueError("{} needs {} weights, got {}".format(algebra.name, expected, size))
        if weights != Counter({tuple(-x for x in w): m for w, m in weights.items()}):
            raise ValueError("The representation must be self-conjugate")
        zero = tuple(Fraction(0) for _ in listed[0])
        positive = [w for w in listed if w > zero]
        images = positive + [zero] * (n - len(positive))
        if flip:
            images[0] = tuple(-x for x in images[0])
    else:
        raise ValueError("Defining representations are only used for SU(N), SO(N) and Sp(N)")
    rows = [[sum((omegas[i][j] * images[j][r] for j in range(len(images))), Fraction(0)) for i in range(n)]
            for r in range(len(listed[0]))]
    # the defining representation must come out as given
    raw = Embedding([algebra], factors, rows, description)
    projected = Counter()
    for w, m in LieIrrep(algebra, fundamental(algebra, 1)).weights().items():
        projected[raw.project(w)] += m
    if projected != weights:
        raise ValueError("Internal error: the projection does not reproduce the defining representation")
    start = 0
    for f in factors:
        if is_u1(f) and normalize:
            rows[start] = normalized_charges(rows[start])
        start += f.rank
    return check_embedding(Embedding([algebra], factors, rows, description))


# Principal SU(2): the label of lambda is <lambda, 2 rho^vee> = 2 x (sum of its coordinates in simple roots)
def principal_embedding(algebra):
    inverse = cartan_inverse(algebra)
    row = [2 * sum(inverse[j]) for j in range(algebra.rank)]
    return check_embedding(Embedding([algebra], [SimpleLieAlgebra('A', 1)], [row], "principal SU(2)"))


def identity_embedding(factor):
    return Embedding([factor], [factor], [[int(i == j) for j in range(factor.rank)] for i in range(factor.rank)],
                     'identity')


# Isomorphisms between algebras of different names: SO(6) = SU(4), SO(5) = Sp(4)
ISOMORPHISMS = {('D', 3, 'A', 3): [[0, 1, 0], [1, 0, 0], [0, 0, 1]],
                ('A', 3, 'D', 3): [[0, 1, 0], [1, 0, 0], [0, 0, 1]],
                ('B', 2, 'C', 2): [[0, 1], [1, 0]], ('C', 2, 'B', 2): [[0, 1], [1, 0]]}


def canonical_type(factor):
    if is_u1(factor):
        return 'U1'
    key = (factor.series, factor.rank)
    return {('D', 3): ('A', 3), ('C', 2): ('B', 2)}.get(key, key)


def isomorphism(source, target):
    if source == target:
        return identity_embedding(source)
    matrix = ISOMORPHISMS.get((source.series, source.rank, target.series, target.rank))
    if matrix is None:
        raise ValueError("{} and {} are not isomorphic".format(source.name, target.name))
    return Embedding([source], [target], matrix, 'isomorphism')


def matmul(a, b):
    return [[sum((a[i][k] * b[k][j] for k in range(len(b))), Fraction(0)) for j in range(len(b[0]))]
            for i in range(len(a))]


# Block diagonal product of embeddings: parent = concatenation of parents, factors = concatenation of factors
def product_embedding(embeddings):
    parent = [f for e in embeddings for f in e.parent]
    factors = [f for e in embeddings for f in e.factors]
    width = sum(f.rank for f in parent)
    rows = []
    offset = 0
    for e in embeddings:
        for row in e.matrix:
            rows.append([Fraction(0)] * offset + list(row) + [Fraction(0)] * (width - offset - len(row)))
        offset += len(e.matrix[0])
    return Embedding(parent, factors, rows, '')


# first: G > H, second: H > K
def compose(first, second, description=None):
    if second.parent != first.factors:
        raise ValueError("Cannot compose {} with {}".format(first, second))
    if description is None:
        description = '{}, then {}'.format(first.description, second.description)
    return check_embedding(Embedding(first.parent, second.factors, matmul(second.matrix, first.matrix), description))


# Apply 'sub' (an embedding of factor 'index' of 'first') to that factor; its factors take that factor's place
def then(first, index, sub):
    parts = [sub if i == index else identity_embedding(f) for i, f in enumerate(first.factors)]
    description = '{}; then {} ⊃ {}: {}'.format(first.description, sub.parent[0].name, sub.name, sub.description)
    return compose(first, product_embedding(parts), description)


# Reorder the factors of H: new factor i is old factor order[i]
def reorder(embedding, order, description=None):
    blocks = list(embedding.blocks())
    rows = [embedding.matrix[r] for i in order for r in blocks[i][1]]
    return Embedding(embedding.parent, [embedding.factors[i] for i in order], rows,
                     embedding.description if description is None else description)


# Keep only the factors in 'keep' (dropping U(1)s or factors restricts to a smaller subalgebra)
def restrict(embedding, keep):
    return check_embedding(reorder(embedding, keep))


# Relabel factor 'index' by an automorphism of its Dynkin diagram ('permutation' of its nodes) or flip a U(1) sign
def twist(embedding, index, permutation=None, sign=1):
    blocks = list(embedding.blocks())
    rows = [list(row) for row in embedding.matrix]
    rows_of = list(blocks[index][1])
    if permutation is not None:
        old = [rows[r] for r in rows_of]
        for a, r in enumerate(rows_of):
            rows[r] = old[permutation[a]]
    if sign == -1:
        for r in rows_of:
            rows[r] = [-x for x in rows[r]]
    return check_embedding(Embedding(embedding.parent, embedding.factors, rows, embedding.description))


# If K is a subalgebra of both G (given by g_to_k: G > K) and H (h_to_k: H > K, with H and K of the same rank and
# h_to_k.factors == g_to_k.factors), then H is a subalgebra of G with projection inverse(h_to_k) o g_to_k
def lift(g_to_k, h_to_k, description=''):
    if h_to_k.factors != g_to_k.factors:
        raise ValueError("Cannot lift {} through {}".format(g_to_k, h_to_k))
    square = [list(row) for row in h_to_k.matrix]
    if len(square) != len(square[0]):
        raise ValueError("Lifting needs subalgebras of the same rank")
    matrix = matmul(invert(square), g_to_k.matrix)
    return check_embedding(Embedding(g_to_k.parent, h_to_k.parent, matrix, description))




# Merge factors 'indices' (all the same simple algebra) into their diagonal subalgebra, which takes the place of the
# first of them. Factors in 'conjugated' enter through the complex conjugate representation.
def diagonal(embedding, indices, conjugated=()):
    blocks = list(embedding.blocks())
    f = embedding.factors[indices[0]]
    if any(embedding.factors[i] != f for i in indices):
        raise ValueError("Only copies of the same algebra have a diagonal subalgebra")
    width = len(embedding.matrix[0])
    merged = [[Fraction(0)] * width for _ in range(f.rank)]
    for i in indices:
        permutation = conjugation_permutation(f) if i in conjugated else list(range(f.rank))
        for a in range(f.rank):
            row = embedding.matrix[blocks[i][1][permutation[a]]]
            merged[a] = [x + y for x, y in zip(merged[a], row)]
    rows, factors = [], []
    for i, (factor, rows_) in enumerate(blocks):
        if i == indices[0]:
            rows += merged
            factors.append(f)
        elif i not in indices:
            rows += [embedding.matrix[r] for r in rows_]
            factors.append(factor)
    return check_embedding(Embedding(embedding.parent, factors, rows, embedding.description))


# The conjugate of the irrep with labels (a_1, ..., a_n) has labels (a_s(1), ..., a_s(n)); returns s
def conjugation_permutation(algebra):
    result = []
    for i in range(algebra.rank):
        image = algebra.dominant(tuple(-int(i == j) for j in range(algebra.rank)))[0]
        result.append(image.index(1))
    return result


