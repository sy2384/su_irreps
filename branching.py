# Names of the subalgebras that find_embedding knows for g, for the app's suggestions
def known_subgroups(g):
    names = []
    for factors, _ in list(exceptional_candidates(g)) + list(classical_candidates(g)):
        # SO(6) as SU(4), as in Pati-Salam
        names.append('x'.join('SU(4)' if canonical_type(f) == ('A', 3) else f.name for f in factors))
    names.append('SU(2)')
    names += CHAINS.get((g.series, g.rank), [])
    return list(dict.fromkeys(names))
