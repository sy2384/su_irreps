def regular_types(g, extended, nodes):
    # the factor types of deleted_nodes_embedding(g, extended, nodes), without building it
    roots = extended_roots(g)
    kept = ([0] if extended else []) + [i for i in range(1, g.rank + 1) if i != extended and i not in nodes]
    found = identify_diagram(cartan_of_roots(g, [roots[i] for i in kept]))
    return [SimpleLieAlgebra(s, r) for s, r, _ in found] + [U1()] * len(nodes)


# Put the factors of 'embedding' in the order of 'requested', using SO(6) = SU(4) and SO(5) = Sp(4) where needed and
# dropping U(1)s that were not asked for. Returns None when the factors do not match.
def match_factors(embedding, requested):
    found = list(embedding.factors)
    drop_u1 = not any(is_u1(f) for f in requested)
    if drop_u1:
        keep = [i for i, f in enumerate(found) if not is_u1(f)]
    else:
        keep = list(range(len(found)))
    if len(keep) != len(requested):
        return None
    order, used = [], set()
    for f in requested:
        exact = [i for i in keep if i not in used and found[i] == f]
        similar = [i for i in keep if i not in used and canonical_type(found[i]) == canonical_type(f)]
        choice = (exact or similar or [None])[0]
        if choice is None:
            return None
        used.add(choice)
        order.append(choice)
    result = reorder(embedding, order)
    for i, f in enumerate(requested):
        if result.factors[i] != f:
            result = then(result, i, isomorphism(result.factors[i], f))
    result.description = embedding.description
    return check_embedding(result)


def type_multiset(factors, ignore_u1=False):
    return sorted(str(canonical_type(f)) for f in factors if not (ignore_u1 and is_u1(f)))


# Find an embedding of the subalgebra with the given factors in g: first the named ones (with the usual physics
# conventions), then regular subalgebras from deleting nodes, then the principal SU(2)
def find_embedding(g, requested):
    requested = list(requested)
    wanted = type_multiset(requested)
    u1s = sum(1 for f in requested if is_u1(f))
    named_list = list(exceptional_candidates(g)) + list(classical_candidates(g))
    # named ones with the same factors, then (when no U(1) is requested) named ones with extra U(1)s, which are dropped
    for drop in ([False, True] if not u1s else [False]):
        for factors, build in named_list:
            if drop and not any(is_u1(f) for f in factors):
                continue
            if type_multiset(factors, ignore_u1=drop) == wanted:
                result = match_factors(build(), requested)
                if result is not None:
                    return result
    # regular subalgebras with the same factors; then the principal SU(2); then (when no U(1) is requested) regular
    # subalgebras with up to two extra U(1)s, which are dropped
    extras = [(u1s, False)] + ([] if u1s else [(1, True), (2, True)])
    for extra, drop in extras:
        if drop and requested == [A1]:
            return principal_embedding(g)
        for extended in [None] + list(range(1, g.rank + 1)):
            for nodes in combinations([i for i in range(1, g.rank + 1) if i != extended], extra):
                if extended is None and not nodes:
                    continue
                types = regular_types(g, extended, nodes)
                if type_multiset(types, ignore_u1=drop) != wanted:
                    continue
                result = match_factors(deleted_nodes_embedding(g, extended=extended, deleted=nodes), requested)
                if result is not None:
                    return result
    if requested == [A1]:
        return principal_embedding(g)
    raise ValueError("Could not find {} in {}".format(algebra_name(requested), g.name))


FACTOR_ALIASES = {'SO(2)': 'U(1)', 'SO(3)': 'SU(2)', 'SP(2)': 'SU(2)', 'USP(2)': 'SU(2)'}


def parse_factor(text):
    text = text.strip()
    key = re.sub(r'\s+', '', text).upper()
    key = FACTOR_ALIASES.get(key, key)
    if key == 'U(1)' or key == 'U1':
        return [U1()]
    if key in ('SO(4)',):
        return [A1, A1]
    return [lie_algebra(key)]


def parse_factors(text):
    parts = [p for p in re.split(r'[x×*]', text.replace('X', 'x')) if p.strip()]
    if not parts:
        raise ValueError("Empty subalgebra")
    return [f for p in parts for f in parse_factor(p)]


# Embedding from a description like 'SU(3)xSU(2)xU(1)', or a chain 'SU(5)xU(1) > SU(3)xSU(2)xU(1)xU(1)', where
# each step breaks one factor of the previous one and the new factors take its place
def embedding(group, subgroup):
    g = lie_algebra(group) if isinstance(group, str) else group
    steps = [s for s in re.split(r'>|⊃', subgroup) if s.strip()]
    if not steps:
        raise ValueError("Enter a subgroup")
    current = find_embedding(g, parse_factors(steps[0]))
    for step in steps[1:]:
        current = break_one_factor(current, parse_factors(step))
    return current


def break_one_factor(current, requested):
    factors = list(current.factors)
    for index, f in enumerate(factors):
        if is_u1(f):
            continue
        others = factors[:index] + factors[index + 1:]
        remaining = list(requested)
        for o in others:
            matches = [i for i, r in enumerate(remaining) if r == o]
            if not matches:
                break
            remaining.pop(matches[0])
        else:
            if not remaining:
                continue
            try:
                sub = find_embedding(f, remaining)
            except ValueError:
                continue
            result = match_factors(then(current, index, sub), requested)
            if result is not None:
                result.description = '{}; then {} ⊃ {}: {}'.format(current.description, f.name, sub.name,
                                                                   sub.description)
                return result
    raise ValueError("Could not get {} from {}".format(algebra_name(requested), current.name))


# Branchings of the smallest irreps of G, to show the conventions of an embedding
def describe(embedding, count=2):
    g = embedding.parent[0]
    irreps = sorted((LieIrrep(g, fundamental(g, i + 1)) for i in range(g.rank)), key=lambda r: (r.dim, r.bar))
    shown, seen = [], set()
    for irrep in irreps:
        if irrep.conjugate().labels in seen:
            continue
        seen.add(irrep.labels)
        shown.append(format_branching(irrep, branch(irrep, embedding)))
        if len(shown) == count:
            break
    return shown


