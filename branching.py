A1 = SimpleLieAlgebra('A', 1)


def fundamental(algebra, i):
    return tuple(int(j == i - 1) for j in range(algebra.rank))


# Small classical groups as factors, with the components of their defining representation:
# SU(1) and SO(1) are nothing, SO(2) = U(1) with charges +-1, SO(3) = SU(2) with the triplet, SO(4) = SU(2) x SU(2)
# with (2, 2), Sp(2) = SU(2)
def su_block(n):
    if n == 1:
        return [], [[]]
    g = SimpleLieAlgebra('A', n - 1)
    return [g], [[fundamental(g, 1)]]


def so_block(n):
    if n == 1:
        return [], [[]]
    if n == 2:
        return [U1()], [[Fraction(1)], [Fraction(-1)]]
    if n == 3:
        return [A1], [[(2,)]]
    if n == 4:
        return [A1, A1], [[(1,), (1,)]]
    g = SimpleLieAlgebra('B', (n - 1) // 2) if n % 2 else SimpleLieAlgebra('D', n // 2)
    return [g], [[fundamental(g, 1)]]


def sp_block(n):
    g = A1 if n == 2 else SimpleLieAlgebra('C', n // 2)
    return [g], [[fundamental(g, 1)]]


def trivial(factors):
    return [Fraction(0) if is_u1(f) else (0,) * f.rank for f in factors]


def direct_sum(blocks):
    factors = [f for fs, _ in blocks for f in fs]
    components, offset = [], 0
    for fs, comps in blocks:
        for parts in comps:
            c = trivial(factors)
            c[offset:offset + len(fs)] = parts
            components.append(c)
        offset += len(fs)
    return factors, components


def tensor_product(blocks):
    factors = [f for fs, _ in blocks for f in fs]
    return factors, [[p for parts in combination for p in parts] for combination in product(*(c for _, c in blocks))]


def from_defining(g, factors, components, description, flip=False):
    return lambda: defining_rep_embedding(g, factors, components, description, flip=flip)


# Subalgebras of SU(N), SO(N), Sp(N) as (factors, builder); builders are only called for the requested factors
def classical_candidates(g):
    n = g.rank
    if g.series == 'A':
        N = n + 1
        for p in range(N - 1, (N - 1) // 2, -1):  # SU(p) x SU(q) x U(1), p + q = N: N = (p, 1)(-q) + (1, q)(p)
            q = N - p
            (fp, cp), (fq, cq) = su_block(p), su_block(q)
            factors = fp + fq + [U1()]
            comps = [cp[0] + trivial(fq) + [Fraction(-q)], trivial(fp) + cq[0] + [Fraction(p)]]
            yield factors, from_defining(g, factors, comps, "regular, defining representation split")
        for p in range(2, N):  # SU(pq) > SU(q) x SU(p), q >= p: N = (q, p)
            q = N // p
            if p * q == N and q >= p:
                factors, comps = tensor_product([su_block(q), su_block(p)])
                yield factors, from_defining(g, factors, comps, "special, defining representation = tensor product")
        if N >= 3 and N != 4:  # SO(N); SO(4) = SU(2) x SU(2) is the case above
            factors, comps = so_block(N)
            yield factors, from_defining(g, factors, comps, "special, defining representation = vector of SO({})"
                                         .format(N))
        if N >= 4 and N % 2 == 0:  # Sp(N)
            factors, comps = sp_block(N)
            yield factors, from_defining(g, factors, comps, "special, defining representation of Sp({})".format(N))
    elif g.series in 'BD':
        N = 2 * n + 1 if g.series == 'B' else 2 * n
        for p in range(N - 1, (N - 1) // 2, -1):  # SO(p) x SO(q), p + q = N: vector = (p, 1) + (1, q)
            factors, comps = direct_sum([so_block(p), so_block(N - p)])
            kind = "special" if g.series == 'B' and p % 2 and (N - p) % 2 else "regular"
            yield factors, from_defining(g, factors, comps, kind + ", vector representation split")
        if g.series == 'D':  # SU(n) x U(1): vector = n(1) + nbar(-1)
            h = SimpleLieAlgebra('A', n - 1)
            factors = [h, U1()]
            comps = [[fundamental(h, 1), Fraction(1)], [fundamental(h, n - 1), Fraction(-1)]]
            # with this sign the 16 of SO(10) is 10(-1) + 5bar(3) + 1(-5), as in Slansky
            yield factors, from_defining(g, factors, comps, "regular, vector = n + nbar")
        for p in range(3, N):  # SO(pq) > SO(q) x SO(p), q > p >= 3: vector = (q, p)
            q = N // p
            if p * q == N and q > p:
                factors, comps = tensor_product([so_block(q), so_block(p)])
                yield factors, from_defining(g, factors, comps, "special, vector = tensor product")
        for p in range(1, N):  # SO(4pq) > Sp(2q) x Sp(2p), q >= p: vector = (2q, 2p)
            if N % (4 * p) == 0 and N // (4 * p) >= p:
                factors, comps = tensor_product([sp_block(N // (2 * p)), sp_block(2 * p)])
                yield factors, from_defining(g, factors, comps, "special, vector = tensor product")
        if N == 7:
            h = SimpleLieAlgebra('G', 2)
            yield [h], from_defining(g, [h], [[(1, 0)]], "special, vector 7 of SO(7) = 7 of G2")
        if N == 8:  # the other SO(7) of SO(8), under which the vector is the spinor of SO(7)
            h = SimpleLieAlgebra('B', 3)
            yield [h], from_defining(g, [h], [[(0, 0, 1)]], "special, vector 8 of SO(8) = spinor of SO(7)")
    elif g.series == 'C':
        N = 2 * n
        for p in range(n - 1, (n - 1) // 2, -1):  # Sp(2p) x Sp(2q), p + q = n
            factors, comps = direct_sum([sp_block(2 * p), sp_block(2 * (n - p))])
            yield factors, from_defining(g, factors, comps, "regular, defining representation split")
        h = SimpleLieAlgebra('A', n - 1)  # SU(n) x U(1): 2n = n(1) + nbar(-1)
        factors = [h, U1()]
        comps = [[fundamental(h, 1), Fraction(1)], [fundamental(h, n - 1), Fraction(-1)]]
        yield factors, from_defining(g, factors, comps, "regular, defining representation = n + nbar")
        for p in range(1, n + 1):  # Sp(2pq) > Sp(2p) x SO(q), q >= 3: 2pq = (2p, q)
            q = n // p
            if p * q == n and q >= 3:
                factors, comps = tensor_product([sp_block(2 * p), so_block(q)])
                yield factors, from_defining(g, factors, comps, "special, defining representation = tensor product")


def named(embedding, description):
    embedding.description = description
    return embedding


def maximal_regular(g, node, order=None, twists=(), description=None):
    e = deleted_nodes_embedding(g, extended=node)
    if order is not None:
        e = reorder(e, order)
    for index, permutation in twists:
        e = twist(e, index, permutation)
    return named(e, description or "regular, maximal: delete node {} of the extended Dynkin diagram".format(node))


def levi(g, nodes, order=None, twists=(), signs=(), description=None):
    e = deleted_nodes_embedding(g, deleted=nodes)
    if order is not None:
        e = reorder(e, order)
    for index, permutation in twists:
        e = twist(e, index, permutation)
    for index in signs:
        e = twist(e, index, sign=-1)
    return named(e, description or "regular: delete node(s) {} of the Dynkin diagram".format(
        ', '.join(str(x) for x in nodes)))


def family(g, factors):
    # the classical-family embedding of g with exactly these factors
    for fs, build in classical_candidates(g):
        if list(fs) == list(factors):
            return build()
    raise ValueError("No such classical subalgebra")


def alg(name):
    return lie_algebra(name)


